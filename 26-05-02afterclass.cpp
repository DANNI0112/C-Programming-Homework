/*指针数组排序
本题已提供可见的 main.c。请只提交函数 sort_ptrs 的实现，不要编写 main，也不要提交 main.c。

main 会把 n 个整数读入数组 a，再建立指针数组，令每个 p[i] 指向 a[i]，然后调用：

void sort_ptrs(int *p[], int n);

请只交换 p 里的指针，使 *p[0] 到 *p[n - 1] 按升序排列。比较大小时使用 *p[i]，交换的必须是指针本身。函数返回后，每个 p[i] 仍要指向 a 中互不相同的元素，不得改动 a 里整数原来的存放顺序。

main 会检查这些指针是不是 a 中元素的一个排列。若有指针指向了别处，或两个指针指向同一个元素，程序输出 invalid。检查通过后，第一行输出 a 的原顺序，第二行输出 *p[i] 的升序结果。

因此：如果交换的是 *p[i] 指向的整数，原数组顺序会被打乱，第一行就会错误；如果只排序另一份数据、却不调整 p，第二行也不会变成升序。

输入格式： 第一行一个整数 n（1 ≤ n ≤ 20）。第二行 n 个整数，每个整数在 -1000 到 1000 之间，同行整数以空格分隔。

输出格式： 两行，每行 n 个整数。第一行为原数组的输入顺序，第二行为升序结果；同行相邻整数间恰好一个空格，行末换行。

样例输入：

5
3 -1 8 0 6

样例输出：

3 -1 8 0 6
-1 0 3 6 8

*/
#include <stdio.h>
void sort_ptrs(int *p[], int n){
    for (int i=0;i<n-1;i++){//用来遍历比较轮次数
    	for (int j=0;j<n-1-i;j++){//每一轮比较相邻的元素，注意防止越界访问，每轮得到该轮次最大元素
    		if (*p[j]>*p[j+1]){
    			int *t=p[j];
    			p[j]=p[j+1];
    			p[j+1]=t;
			}
		}
	}
}
